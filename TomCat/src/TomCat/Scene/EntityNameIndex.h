#pragma once

#include <charconv>
#include <cstddef>
#include <cstdint>
#include <string>
#include <unordered_map>

namespace TomCat {

	// A scoped index, not a persistent Scene cache: native authoring code can
	// mutate Tag strings directly. Scene copies own one while creating identities;
	// deferred projections own one alongside their controlled metadata state.
	class EntityNameIndex
	{
	public:
		void Reserve(size_t count) { m_Names.reserve(count); }
		void Add(const std::string& name) { ++m_Names[name]; }
		void Remove(const std::string& name)
		{
			const auto found = m_Names.find(name);
			if (found == m_Names.end())
				return;
			if (--found->second == 0)
			{
				m_Names.erase(found);
				// Only the exact canonical suffix generated by MakeUnique can open
				// a hole in a cursor's occupied prefix. The final delimiter also
				// handles literal/nested bases such as "Arc (1) (2)" correctly.
				const auto delimiter = name.rfind(" (");
				if (delimiter == std::string::npos || name.back() != ')')
					return;
				const auto first = name.data() + delimiter + 2;
				const auto last = name.data() + name.size() - 1;
				if (first == last || *first < '1' || *first > '9')
					return;
				uint32_t released = 0;
				const auto parsed = std::from_chars(first, last, released);
				if (parsed.ec != std::errc{} || parsed.ptr != last)
					return;
				const auto cursor = m_NextSuffix.find(name.substr(0, delimiter));
				if (cursor != m_NextSuffix.end() && released < cursor->second)
					cursor->second = released;
			}
		}
		std::string MakeUnique(const std::string& requestedName)
		{
			const std::string base = requestedName.empty() ? "Entity" : requestedName;
			++m_Probes;
			if (!m_Names.contains(base))
				return base;
			auto& suffix = m_NextSuffix[base];
			if (suffix == 0)
				suffix = 1;
			for (;; ++suffix)
			{
				std::string candidate = base + " (" + std::to_string(suffix) + ")";
				++m_Probes;
				if (!m_Names.contains(candidate))
					return candidate;
			}
		}
		uint64_t GetProbeCount() const { return m_Probes; }
	private:
		std::unordered_map<std::string, size_t> m_Names;
		std::unordered_map<std::string, uint32_t> m_NextSuffix;
		uint64_t m_Probes = 0;
	};
}
